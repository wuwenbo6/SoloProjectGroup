const acknowledgeAlert = async (req, res) => {
  try {
    const { alertId, notes } = req.body;

    const alert = await ParameterAlert.findById(alertId);
    if (!alert) {
      return res.status(404).json({
        success: false,
        message: '预警记录不存在'
      });
    }

    alert.status = 'acknowledged';
    alert.acknowledgedBy = req.user.id;
    alert.acknowledgedAt = new Date();

    if (notes) {
      alert.actions.push({
        action: 'acknowledged',
        performedBy: req.user.id,
        notes
      });
    }

    await retryOperation(() => alert.save(), 3, 500);

    logger.info('预警已确认', { alertId, userId: req.user.id });

    res.json({
      success: true,
      message: '预警已确认',
      data: { alert }
    });
  } catch (error) {
    logger.error('确认预警失败:', error);
    res.status(500).json({
      success: false,
      message: '确认预警失败',
      error: error.message
    });
  }
};

